/**
 * Returns the 10 quiz questions for a given tense ID (1..16) or name.
 */
export function getQuizForTense(tenseId: string | number): QuizQuestion[] {
  const key = String(tenseId);
  return TENSE_QUIZ_MAP[key] || SIMPLE_PRESENT_QUIZ;
}

